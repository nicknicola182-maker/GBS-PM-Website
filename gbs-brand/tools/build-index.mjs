// Writes INDEX.md: a navigable list of every deliverable in the pack (PDF, PNG, SVG, DOCX, HTML sources, docs), grouped by folder.
import fs from "node:fs"; import path from "node:path";
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const SKIP = new Set(["node_modules", ".git", "public", "fonts"]);
const KIND = { ".pdf": "PDF", ".png": "PNG", ".svg": "SVG", ".docx": "Word", ".ico": "Icon", ".md": "Doc", ".txt": "Text", ".csv": "CSV", ".html": "HTML source", ".json": "JSON", ".gpl": "Palette", ".css": "CSS", ".mjs": "Script", ".py": "Script", ".sh": "Script", ".jsonc": "Config" };
const groups = {};
const walk = (dir, rel) => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    if (SKIP.has(e.name) || e.name.startsWith(".")) continue;
    const r = path.join(rel, e.name);
    if (e.isDirectory()) walk(path.join(dir, e.name), r);
    else { const top = rel.split(path.sep)[0] || "(root)"; (groups[top] ||= []).push({ r, size: fs.statSync(path.join(dir, e.name)).size, kind: KIND[path.extname(e.name).toLowerCase()] || "File" }); }
  }
};
walk(ROOT, "");
const fmt = n => n > 1048576 ? (n / 1048576).toFixed(1) + " MB" : n > 1024 ? Math.round(n / 1024) + " KB" : n + " B";
let out = `# Pack index\n\nGenerated by \`tools/build-index.mjs\`. ${Object.values(groups).flat().length} files. Rendered outputs (PDF, PNG, Word) sit next to their HTML sources.\n`;
for (const g of Object.keys(groups).sort()) {
  const files = groups[g].filter(f => !/_\d+px_v|\/png\/|\/favicon\//.test(f.r) || /logo-/.test(f.r)); // collapse the large PNG export sets
  const pngs = groups[g].length - files.length;
  out += `\n## ${g}\n\n| File | Type | Size |\n|---|---|---|\n` + files.map(f => `| [${f.r}](${f.r.split(path.sep).map(encodeURIComponent).join("/")}) | ${f.kind} | ${fmt(f.size)} |`).join("\n") + "\n";
  if (pngs) out += `\n${pngs} PNG export files not listed individually (see folder).\n`;
}
fs.writeFileSync(path.join(ROOT, "INDEX.md"), out);
console.log(`INDEX.md: ${Object.values(groups).flat().length} files indexed`);
